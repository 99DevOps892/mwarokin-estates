class CameraStatus(Enum):
    """Camera operational status"""
    ONLINE = "online"
    OFFLINE = "offline"
    STREAMING = "streaming"
    RECORDING = "recording"
    ERROR = "error"


class MotionStatus(Enum):
    """Motion detection status"""
    NO_MOTION = "no_motion"
    MOTION_DETECTED = "motion_detected"
    CONTINUOUS_MOTION = "continuous_motion"


class AlertSeverity(Enum):
    """Alert severity levels"""
    INFO = "info"
    WARNING = "warning"
    CRITICAL = "critical"
    EMERGENCY = "emergency"


class ZoneType(Enum):
    """Type of camera zone"""
    INTERIOR = "interior"
    EXTERIOR = "exterior"
    ENTRY = "entry"
    GARDEN = "garden"
    GARAGE = "garage"
    NURSERY = "nursery"
    KITCHEN = "kitchen"


@dataclass
class Camera:
    """Camera entity with state and metadata"""
    id: int
    name: str
    property_name: str
    zone_type: ZoneType
    status: CameraStatus = CameraStatus.ONLINE
    motion_status: MotionStatus = MotionStatus.NO_MOTION
    staff_attending: Optional[str] = None
    hue: int = 150
    brightness: float = 0.5
    last_motion_detected: Optional[datetime] = None
    stream_url: Optional[str] = None
    recording: bool = False
    snapshot_taken_at: Optional[datetime] = None
    firmware_version: str = "2.1.0"
    ip_address: str = "192.168.1.100"
    uptime_seconds: int = 0
    
    def to_dict(self) -> Dict:
        """Convert camera to dictionary"""
        return {
            "id": self.id,
            "name": self.name,
            "property_name": self.property_name,
            "zone_type": self.zone_type.value,
            "status": self.status.value,
            "motion_status": self.motion_status.value,
            "staff_attending": self.staff_attending,
            "last_motion_detected": self.last_motion_detected.isoformat() if self.last_motion_detected else None,
            "recording": self.recording,
            "uptime_seconds": self.uptime_seconds,
            "firmware_version": self.firmware_version
        }


@dataclass
class MotionEvent:
    """Motion detection event"""
    camera_id: int
    camera_name: str
    property_name: str
    timestamp: datetime
    duration_seconds: float
    motion_level: int  # 1-10
    region: str = "unknown"
    detected_by: str = "ai-detector"
    recorded_clip: Optional[str] = None
    
    def to_dict(self) -> Dict:
        return {
            "camera_id": self.camera_id,
            "camera_name": self.camera_name,
            "property_name": self.property_name,
            "timestamp": self.timestamp.isoformat(),
            "duration_seconds": self.duration_seconds,
            "motion_level": self.motion_level,
            "region": self.region,
            "detected_by": self.detected_by,
            "recorded_clip": self.recorded_clip
        }


@dataclass
class Alert:
    """Alert generated by the system"""
    id: str
    camera_id: int
    camera_name: str
    severity: AlertSeverity
    message: str
    timestamp: datetime
    acknowledged: bool = False
    resolved: bool = False
    metadata: Dict[str, Any] = field(default_factory=dict)
    
    def to_dict(self) -> Dict:
        return {
            "id": self.id,
            "camera_id": self.camera_id,
            "camera_name": self.camera_name,
            "severity": self.severity.value,
            "message": self.message,
            "timestamp": self.timestamp.isoformat(),
            "acknowledged": self.acknowledged,
            "resolved": self.resolved,
            "metadata": self.metadata
        }


@dataclass
class StaffPresence:
    """Staff presence tracking"""
    staff_name: str
    camera_id: int
    property_name: str
    check_in: datetime
    check_out: Optional[datetime] = None
    zone: str = ""
    
    @property
    def duration_hours(self) -> float:
        if self.check_out:
            return (self.check_out - self.check_in).total_seconds() / 3600
        return (datetime.now() - self.check_in).total_seconds() / 3600


